"""Project creation, validation, credential setup and hardware-free preview."""
import argparse, asyncio, getpass, hashlib, json, os, re, secrets, shutil, sys
from pathlib import Path
from urllib.parse import urlsplit

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'platform'))
from definition import load_project

def write_private(path,value):
    path.parent.mkdir(parents=True,exist_ok=True);path.write_text(json.dumps(value,ensure_ascii=False,indent=2),encoding='utf-8');os.chmod(path,0o600)

def configure(folder,origin,username,password):
    def digest(value):return hashlib.sha256(value.encode()).hexdigest()
    def password_hash(value,salt):return hashlib.pbkdf2_hmac('sha256',value.encode(),bytes.fromhex(salt),600000).hex()
    u=urlsplit(origin)
    if u.path not in ('','/') or u.query or u.fragment or u.username or not u.hostname:raise ValueError('填写网站源地址，不包含路径或查询参数')
    if u.scheme!='https' and not (u.scheme=='http' and u.hostname in ('127.0.0.1','localhost')):raise ValueError('公网必须使用HTTPS，本机演示可使用HTTP')
    if not username or len(username)>100 or len(password)<8 or len(password)>256:raise ValueError('用户名1–100字，密码8–256位')
    target=folder/'private/server.json'
    if target.exists():raise ValueError('配置已存在，拒绝覆盖。修改账号请使用网页，新增部署请使用新目录')
    token=secrets.token_urlsafe(32);salt=secrets.token_hex(16);device='gateway-'+secrets.token_hex(4)
    write_private(target,{'origin':origin.rstrip('/'),'username':username,'password_salt':salt,'password_hash':password_hash(password,salt),'devices':{device:{'token_sha256':digest(token)}}})
    write_private(folder/'private/pairing.json',{'schema':1,'device_id':device,'host':u.hostname,'port':u.port or (443 if u.scheme=='https' else 80),'path':'/gateway/ws','tls':u.scheme=='https','token':token})
    return device

def check(folder,generate=False):
    p=load_project(folder/'project.json');hw=p.get('hardware',{})
    if hw.get('mcu')!='IAP15F2K61S2' or hw.get('esp')!='ESP32-S3 N16R8':raise ValueError('当前固件模板只验证指定硬件；更换硬件需要人工适配')
    if hw.get('clock_hz') not in (11059200,12000000) or hw.get('baud')!=9600:raise ValueError('基础固件验证时钟为11.0592/12MHz，波特率9600')
    if hw.get('rx')!='P3.6' or hw.get('tx')!='P3.7':raise ValueError('当前模板采用RX P3.6、TX P3.7')
    logic=(folder/'firmware/logic.c').read_text(encoding='utf-8')
    for command in p['commands']:
        if '"'+command['wire']+'"' not in logic:raise ValueError('固件尚未实现命令 '+command['wire'])
    if generate:
        (folder/'firmware/project_config.h').write_text(f'/* Generated by tools/project.py check --generate. */\n#define PROJECT_ID "{p["id"]}"\n#define PROJECT_CLOCK {hw["clock_hz"]}UL\n#define PROJECT_BAUD {hw["baud"]}UL\n',encoding='ascii')
    else:
        text=(folder/'firmware/project_config.h').read_text()
        if f'"{p["id"]}"' not in text:raise ValueError('固件项目ID未同步，请运行 check --generate')
    print('配置与命令契约检查通过。尚不能替代编译和实机验收。')
    return p

def initialize(destination,name,ident):
    if destination.exists():raise ValueError('目标目录已存在，拒绝覆盖')
    if not re.fullmatch('[a-z][a-z0-9_]{0,15}',ident):raise ValueError('项目ID须为1–16位小写字母/数字/下划线，以字母开头')
    if not 1<=len(name)<=48:raise ValueError('名称须为1–48字')
    if ROOT == destination or ROOT in destination.parents:raise ValueError('新项目目录必须位于模板目录之外，避免递归复制')
    shutil.copytree(ROOT,destination,ignore=shutil.ignore_patterns('private','__pycache__','.git','.venv','output','prebuilt','build','*.zip','.taste-skill','ui-review'))
    p=json.loads((destination/'project.json').read_text(encoding='utf-8'));p.update(id=ident,name=name,description='基于 LED 示例的新项目，请按需求适配业务')
    (destination/'project.json').write_text(json.dumps(p,ensure_ascii=False,indent=2),encoding='utf-8');check(destination,True)
    print('新项目：',destination,'。填写 docs/项目需求表.md 后交给 AI；当前仍是 LED 示例。')

async def demo(port):
    import tempfile
    from aiohttp import web
    from app import create_app
    from simulator import simulate
    with tempfile.TemporaryDirectory(prefix='link-demo-') as temp:
        folder=Path(temp);configure(folder,f'http://127.0.0.1:{port}','demo','demo1234')
        config=json.loads((folder/'private/server.json').read_text());config['demo']=True
        pair=json.loads((folder/'private/pairing.json').read_text());p=load_project(ROOT/'project.json')
        app=create_app(config,folder/'data',ROOT/'project.json');runner=web.AppRunner(app);await runner.setup();await web.TCPSite(runner,'127.0.0.1',port).start()
        task=asyncio.create_task(simulate(f'http://127.0.0.1:{port}',pair,p))
        print(f'模拟演示：http://127.0.0.1:{port}  用户 demo  密码 demo1234\n仅限本机，不连接任何硬件；Ctrl+C停止，演示数据临时保存。',flush=True)
        try:await asyncio.Event().wait()
        finally:
            task.cancel()
            import contextlib
            with contextlib.suppress(asyncio.CancelledError):await task
            await runner.cleanup()

def main():
    p=argparse.ArgumentParser();sub=p.add_subparsers(dest='cmd',required=True)
    init=sub.add_parser('init');init.add_argument('destination',type=Path);init.add_argument('--name',required=True);init.add_argument('--id',required=True)
    c=sub.add_parser('check');c.add_argument('--generate',action='store_true')
    cfg=sub.add_parser('configure');cfg.add_argument('--origin',required=True);cfg.add_argument('--username',default='admin')
    d=sub.add_parser('demo');d.add_argument('--port',type=int,default=8880)
    a=p.parse_args()
    try:
        if a.cmd=='init':initialize(a.destination.resolve(),a.name,a.id)
        elif a.cmd=='check':check(ROOT,a.generate)
        elif a.cmd=='configure':configure(ROOT,a.origin,a.username,getpass.getpass('网页登录密码（至少8位）：'));print('已生成 private/server.json 与 private/pairing.json，请妥善保管。')
        elif a.cmd=='demo':asyncio.run(demo(a.port))
    except (ValueError,OSError) as e:p.exit(1,str(e)+'\n')
    except KeyboardInterrupt:pass
if __name__=='__main__':main()
